CREATE TABLE dbo.branches (
    branch_code VARCHAR(10)  NOT NULL PRIMARY KEY,
    branch_name VARCHAR(100) NOT NULL,
    region_code CHAR(1)      NOT NULL,
    state_code  CHAR(2)      NOT NULL
);

CREATE TABLE dbo.branch_month_metrics (
    period_month        DATE         NOT NULL,
    branch_code         VARCHAR(10)  NOT NULL,
    loans_funded        INT          NOT NULL,
    deposit_growth_rate DECIMAL(9,4) NOT NULL,
    nps_score           DECIMAL(9,1) NOT NULL,
    delinquent_30d_rate DECIMAL(9,4) NOT NULL,
    delinquent_60d_rate DECIMAL(9,4) NOT NULL,
    digital_active_rate DECIMAL(9,4) NOT NULL,
    CONSTRAINT PK_branch_month_metrics PRIMARY KEY (period_month, branch_code)
);

CREATE TABLE dbo.branch_driver_scores (
    period_month DATE        NOT NULL,
    branch_code  VARCHAR(10) NOT NULL,
    driver       VARCHAR(50) NOT NULL,
    impact       FLOAT       NOT NULL,
    value        FLOAT       NOT NULL,
    CONSTRAINT PK_branch_driver_scores PRIMARY KEY (period_month, branch_code, driver)
);

CREATE TABLE dbo.kpi_glossary (
    kpi_name   VARCHAR(50)  NOT NULL PRIMARY KEY,
    definition VARCHAR(400) NOT NULL,
    owner      VARCHAR(100) NOT NULL
);

